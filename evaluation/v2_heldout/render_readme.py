"""Render evaluation/v2_heldout/README.md from summary.json (deterministic)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABELS = {
    "precision": "Precision",
    "recall": "Recall",
    "f1": "F1",
    "recall_at_5": "Recall@5",
    "recall_at_10": "Recall@10",
    "mrr": "MRR",
    "false_positives": "False positives / task",
    "completed_rate": "Completed rate",
    "partial_rate": "Partial rate",
    "abstained_rate": "Abstention rate",
    "failed_rate": "Failed rate",
}


def f(value, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def pct(value) -> str:
    return "n/a" if value is None else f"{value:+.0%}"


def main() -> None:
    s = json.loads((HERE / "summary.json").read_text())
    config = json.loads((HERE / "config.json").read_text())
    manifest = json.loads((HERE / "manifest.json").read_text())
    block = s["all_runs"]
    lines = [
        "# RIPPLE V2.1.1 held-out evaluation",
        "",
        "> A **new, untouched held-out set**, built and frozen before any run. It",
        "> compares frozen V2.1.1 with the frozen V1 protocol *in the same run*. It",
        "> does not modify or reinterpret the historical final-v1 benchmark.",
        "",
        "Generated by `python evaluation/v2_heldout/render_readme.py` from",
        "`summary.json` (produced by `run_heldout.py analyze` from `raw/`).",
        "",
        "## Frozen setup",
        "",
        (
            f"- System commit `{config['frozen_commit']}` (`src/` tree "
            f"`{config['src_tree_sha1']}`), verified unchanged before every run."
        ),
        (
            f"- V1 = `{config['systems']['V1']['variant']}` "
            f"(`{config['systems']['V1']['config_version']}`); V2.1.1 = "
            f"`{config['systems']['V2.1.1']['variant']}` "
            f"(`{config['systems']['V2.1.1']['config_version']}`)."
        ),
        (
            f"- Model `{config['provider']['model']}` via "
            f"`{config['provider']['base_url_host']}`; no provider seed control."
        ),
        (
            f"- {config['repeats_per_task_per_system']} repeats per task per system, "
            "interleaved V1 then V2.1.1 on the same clone; budgets identical "
            f"({json.dumps(config['budgets'])})."
        ),
        (
            f"- Config `{config['config_sha256']}`, manifest "
            f"`{config['manifest_sha256']}`, frozen {config['date']}."
        ),
        (
            f"- Scoring: {config['scoring']}. Paired repository-cluster bootstrap, "
            f"{config['bootstrap']['samples']} samples, seed {config['bootstrap']['seed']}."
        ),
        "",
        "## Held-out set and overlap audit",
        "",
        (
            f"- {s['tasks']} tasks from {s['repositories']} repositories, at most "
            f"{manifest['provenance']['per_repository_cap']} per repository, every task "
            "with 2-4 gold source files."
        ),
        f"- Selection: {manifest['selection_method']}.",
        f"- Overlap audit: {manifest['overlap_audit']['prior_task_ids_checked']} prior "
        "task IDs from "
        + ", ".join(manifest["overlap_audit"]["prior_sources"])
        + "; overlapping tasks: "
        + (str(len(manifest["overlap_audit"]["overlapping_tasks"])) or "0")
        + "; V2 development repositories excluded: "
        + ", ".join(manifest["overlap_audit"]["excluded_repositories"])
        + ".",
        "- Repositories: "
        + ", ".join(
            f"{repo} ({count})"
            for repo, count in manifest["provenance"]["repositories"].items()
        )
        + ".",
        "",
        "## Results (all scored runs; failures count as zero)",
        "",
        "| Metric | V1 | V2.1.1 | Δ (V2.1.1 − V1) | Relative Δ |",
        "|---|---:|---:|---:|---:|",
    ]
    for key, label in LABELS.items():
        lines.append(
            f"| {label} | {f(block['V1'][key])} | {f(block['V2.1.1'][key])} "
            f"| {f(block['deltas_v2_minus_v1'].get(key))} "
            f"| {pct(block['relative_deltas'].get(key))} |"
        )
    lines += [
        "",
        "## Paired repository-cluster bootstrap (V2.1.1 − V1)",
        "",
        "| Metric | Mean difference | 95% CI | CI excludes 0 |",
        "|---|---:|---:|---|",
    ]
    for key, value in block["paired_bootstrap_v2_minus_v1"].items():
        lines.append(
            f"| {LABELS.get(key, key)} | {f(value['mean_difference'])} "
            f"| [{f(value['ci_low'])}, {f(value['ci_high'])}] "
            f"| {'yes' if value['ci_excludes_zero'] else 'no'} |"
        )
    behaviour = s["behaviour_only"]
    lines += [
        "",
        (
            "Behaviour-only view (provider/harness failures excluded): F1 "
            f"{f(behaviour['V1']['f1'])} vs {f(behaviour['V2.1.1']['f1'])}, precision "
            f"{f(behaviour['V1']['precision'])} vs {f(behaviour['V2.1.1']['precision'])}, "
            f"recall {f(behaviour['V1']['recall'])} vs {f(behaviour['V2.1.1']['recall'])}."
        ),
        "",
        "## Operations",
        "",
        "| Mean per run | V1 | V2.1.1 |",
        "|---|---:|---:|",
    ]
    for key in (
        "tool_calls",
        "model_calls",
        "duplicate_calls",
        "invalid_tool_targets",
        "total_tokens",
        "runtime_seconds",
        "decision_checkpoints",
        "report_repairs",
        "validator_drops",
    ):
        lines.append(
            f"| {key.replace('_', ' ')} | {f(s['operations']['V1'][f'mean_{key}'], 2)} "
            f"| {f(s['operations']['V2.1.1'][f'mean_{key}'], 2)} |"
        )
    lines += [
        "",
        "## Safety",
        "",
        "| | V1 | V2.1.1 |",
        "|---|---:|---:|",
    ]
    for key in (
        "unsupported_accepted_claims",
        "runs_with_unsupported_claims",
        "validator_drops",
        "new_file_classification_drops",
        "runs_with_report_repair",
    ):
        lines.append(
            f"| {key.replace('_', ' ')} | {s['safety']['V1'][key]} "
            f"| {s['safety']['V2.1.1'][key]} |"
        )
    lines += [
        "",
        "## Runs, failures, retries",
        "",
        (
            f"- Scored slots: {s['scored_slots']} of {s['expected_slots']} expected; "
            f"attempts {s['attempts']}."
        ),
        (
            f"- Provider-failed attempts: {s['provider_failed_attempts']}; retries: "
            f"{s['retries']} (one predetermined retry per provider-failed slot); slots "
            f"still failed after retry: {s['slots_failed_after_retry']}."
        ),
        "- Harness errors: "
        + ("; ".join(s["harness_errors"]) if s["harness_errors"] else "none")
        + ".",
        "- Status mix: "
        + "; ".join(
            f"{system}: " + ", ".join(f"{k} {v}" for k, v in mix.items())
            for system, mix in s["status_mix"].items()
        )
        + ".",
    ]
    (HERE / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
